"""Rebuild netorbit_pi/web/icons.js from @mdi/js's mdi.js.

Usage: python3 scripts/gen_icons.py path/to/mdi.js netorbit_pi netorbit_pi/web/icons.js
Keeps every icon the code mentions plus a set for the device icon picker.
"""
import re, sys, pathlib
mdi_js, root, out = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
paths = dict(re.findall(r'export var (mdi\w+) = "([^"]+)";', open(mdi_js).read()))
used = set()
for f in list(root.rglob("*.py")) + list(root.rglob("*.js")) + list(root.rglob("*.html")):
    if f.name == "icons.js": continue
    used |= set(re.findall(r"mdi:([a-z0-9-]+)", f.read_text()))
extra = """desktop-tower desktop-classic raspberry-pi wifi fridge washing-machine doorbell-video lock power-plug fan camera
speaker-wireless cast nintendo-switch sony-playstation microsoft-xbox cog close history logout content-save magnify
refresh plus delete download upload bell cancel eye-off ipod headphones car baby-face-outline dog bed sofa
weather-partly-cloudy solar-power ev-station water-pump smoke-detector alarm-light lan-pending ethernet
router-wireless wifi-cog radar shield-home cellphone-wireless phone-classic printer-3d projector
apple robot-mower lightbulb-group led-strip-variant air-purifier kettle coffee-maker toaster-oven
microwave dishwasher tumble-dryer battery-charging-high home-thermometer water-boiler blinds sprinkler pool
television-guide gamepad-square monitor-dashboard harddisk server-network archive help-circle alert""".split()
want = sorted(used | set(extra))
missing = []
lines = ["// Material Design Icons (Apache-2.0, https://pictogrammers.com), only the ones NetOrbit uses.",
         "// Generated by scripts/gen_icons.py from @mdi/js 7.4.47.", "window.NETORBIT_ICONS = {"]
for name in want:
    key = "mdi" + "".join(p.capitalize() for p in name.split("-"))
    if key not in paths:
        if name in extra:
            missing.append(name)
        continue
    lines.append(f'  "{name}": "{paths[key]}",')
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print("icons written:", sum(1 for l in lines if l.startswith("  \"")), "missing from picker list:", missing)
